import { CountryListItem, CountryIndicatorSummary, IndicatorKey } from '../types';
import { INDICATOR_CONFIGS } from '../utils/normalize';
import { formatPopulation, formatArea } from '../utils/format';
import { AIInsightsData } from '../components/compare/AIInsights';

export interface ReportData {
  countries: CountryListItem[];
  indicators?: Record<string, Record<IndicatorKey, CountryIndicatorSummary>>;
  insights?: AIInsightsData | null;
}

/**
 * Generates an executive Markdown report string for download or copy.
 */
export function generateMarkdownReport(data: ReportData): string {
  const { countries, indicators, insights } = data;
  const now = new Date();
  const dateStr = now.toLocaleDateString('en-US', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const countryNames = countries.map((c) => `${c.name.common} (${c.cca3})`).join(' vs ');

  let md = `# Country Comparison Report: ${countryNames}\n\n`;
  md += `**Generated by:** Atlas Compare (World Bank Open Data & Gemini AI)\n`;
  md += `**Date:** ${dateStr}\n\n`;
  md += `---\n\n`;

  // 1. Executive Summary & AI Insights
  if (insights) {
    md += `## 1. Executive AI Synthesis\n\n`;
    md += `> ${insights.summary}\n\n`;

    md += `### Key Relative Strengths\n`;
    insights.strengths.forEach((item) => {
      md += `\n**${item.country}:**\n`;
      item.points.forEach((pt) => {
        md += `- ${pt}\n`;
      });
    });

    md += `\n### Watch-outs & Growth Areas\n`;
    insights.weaknesses.forEach((item) => {
      md += `\n**${item.country}:**\n`;
      item.points.forEach((pt) => {
        md += `- ${pt}\n`;
      });
    });

    md += `\n### Analytical Verdict\n`;
    md += `${insights.verdict}\n\n`;
    md += `---\n\n`;
  }

  // 2. Core Demographics
  md += `## 2. Demographics & Geographic Profiles\n\n`;
  md += `| Attribute | ${countries.map((c) => c.name.common).join(' | ')} |\n`;
  md += `| :--- | ${countries.map(() => ':---').join(' | ')} |\n`;
  md += `| ISO Code | ${countries.map((c) => c.cca3).join(' | ')} |\n`;
  md += `| Region / Subregion | ${countries.map((c) => `${c.region} (${c.subregion || 'N/A'})`).join(' | ')} |\n`;
  md += `| Capital | ${countries.map((c) => c.capital?.join(', ') || 'N/A').join(' | ')} |\n`;
  md += `| Population | ${countries.map((c) => formatPopulation(c.population)).join(' | ')} |\n`;
  md += `| Total Area | ${countries.map((c) => formatArea(c.area)).join(' | ')} |\n\n`;

  // 3. World Bank Indicators Matrix
  if (indicators) {
    md += `## 3. World Bank Indicator Benchmark\n\n`;
    md += `| Indicator | ${countries.map((c) => c.name.common).join(' | ')} |\n`;
    md += `| :--- | ${countries.map(() => ':---').join(' | ')} |\n`;

    const indicatorKeys = Object.keys(INDICATOR_CONFIGS) as IndicatorKey[];
    indicatorKeys.forEach((key) => {
      const cfg = INDICATOR_CONFIGS[key];
      const values = countries.map((c) => {
        const ind = indicators[c.cca3]?.[key];
        if (ind?.latestValue !== null && ind?.latestValue !== undefined) {
          return `${ind.latestValue.toLocaleString()} ${cfg.unit} (${ind.latestYear || 'recent'})`;
        }
        return 'N/A';
      });
      md += `| ${cfg.label} | ${values.join(' | ')} |\n`;
    });
    md += `\n---\n\n`;
  }

  md += `*Report created with Atlas Compare — Public Data Explorer & AI Benchmark System.*\n`;
  return md;
}

/**
 * Generates CSV data for export.
 */
export function generateCSVReport(data: ReportData): string {
  const { countries, indicators } = data;
  const headers = ['Indicator / Metric', ...countries.map((c) => `"${c.name.common} (${c.cca3})"` )];
  const rows: string[][] = [];

  rows.push(['Region', ...countries.map((c) => `"${c.region}"`)]);
  rows.push(['Subregion', ...countries.map((c) => `"${c.subregion || 'N/A'}"`)]);
  rows.push(['Capital', ...countries.map((c) => `"${c.capital?.join(', ') || 'N/A'}"`)]);
  rows.push(['Population', ...countries.map((c) => `"${c.population || 0}"`)]);
  rows.push(['Area (sq km)', ...countries.map((c) => `"${c.area || 0}"`)]);

  if (indicators) {
    const indicatorKeys = Object.keys(INDICATOR_CONFIGS) as IndicatorKey[];
    indicatorKeys.forEach((key) => {
      const cfg = INDICATOR_CONFIGS[key];
      const vals = countries.map((c) => {
        const ind = indicators[c.cca3]?.[key];
        return ind?.latestValue !== null && ind?.latestValue !== undefined
          ? `"${ind.latestValue} (${ind.latestYear || 'recent'})"`
          : '"N/A"';
      });
      rows.push([`"${cfg.label} (${cfg.unit})"`, ...vals]);
    });
  }

  const csvContent = [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
  return csvContent;
}

/**
 * Triggers file download in the browser.
 */
export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
